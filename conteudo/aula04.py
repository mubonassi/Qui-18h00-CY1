#Calculando com variáveis
#Calculando com numero
num1 = 10
num2 = 20
res = num1+num2
print(f"{num1}+{num2}={res}")

#Calculando com string
txt1 = "a"
txt2 = "b"
res = txt1+txt2
print(res)

#Calculando com numero com input

#Conversão de valores
#tipo()
#ex: int("13")
#ex: float("45.45")
#int() -> input()
num1 = int(input("Digite o número 1: "))
num2 = int(input("Digite o número 2: "))
res = num1+num2
print(f"{num1} + {num2} = {res}")